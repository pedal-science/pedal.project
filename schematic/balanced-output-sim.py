#!/usr/bin/env python3
"""Simulate one balanced output channel in LTspice, and write what it shows.

The circuit is the one in schematic/balanced-output/balanced-output.kicad_sch (the wiring table
is schematic/balanced-output.py); this file restates it as a SPICE netlist with the same
references, and runs five tests against it:

  ac      gain on Line and on Mic, hot and cold separately and together, and how far the mute
          takes it down; the -3 dB points
  cmrr    a 50 Hz and a 1 kHz voltage between the pedal's ground and the receiver's, with the
          two output capacitors matched, 5 % apart and 20 % apart
  powerup the 9 V arriving, the codec's VMID rising behind the mute, the mute releasing, then
          signal: the thump the receiver sees at each step
  phantom 48 V phantom switched on into the outputs, then hot shorted to pin 1 with the
          capacitor charged: what the clamps and the op-amp carry

The op-amp is a behavioural model from the kicad-happy SPICE skill's generator
(spice_model_generator.generate_opamp_model), given the OPA2197's datasheet figures: 10 MHz GBW,
20 V/us, 25 uV offset, 140 dB open-loop gain, rail-to-rail. It has no output current limit, so
the phantom test reports the current the op-amp would have to carry rather than showing it
limit. The 1N5817 is LTspice's own model card. Bipolar capacitors are ideal capacitors with a
small ESR.

    python3 schematic/balanced-output-sim.py [--out DIR] [--ltspice PATH]

Results go to bench-results/<date>-balanced-output-sim/: the .cir files, LTspice's logs and
README.md. The .raw waveforms are deleted once read, unless --keep-raw.
"""
import argparse
import datetime
import math
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LTSPICE = '/Applications/LTspice.app/Contents/MacOS/LTspice'

OPAMP = """\
* Generated by kicad-happy's spice_model_generator.generate_opamp_model('OPA2197', ...)
.subckt OPAMP_OPA2197 inp inn out vcc vee
Rin inp inn 10T
Vos inp inp_os DC 2.5e-05
E1 int 0 inp_os inn 10000000
R1 int out_int 1
C1 out_int 0 159.2m
Dhigh out_int vcc_int DLIMIT
Dlow vee_int out_int DLIMIT
Vswh vcc vcc_int DC 0
Vswl vee_int vee DC 0
.model DLIMIT D(IS=1e-14 N=0.01)
Eout out 0 out_int 0 1
.ends OPAMP_OPA2197
"""

MODELS = """\
.model DSCH D(Is=31.7u Rs=.051 N=1.373 Cjo=190p M=.3 Eg=.69 Xti=2 BV=20 IBV=1m)
.model RELAY SW(Ron=.025 Roff=1G Vt=.5 Vh=0)
.model PADSW SW(Ron=.05 Roff=1G Vt=.5 Vh=0)
"""


def channel(c18='47u', supply='VSUP sup 0 DC 9', hpl='VHP hpl 0 DC 1.65 AC 1',
            mic='0', mute='0', esr='0.5'):
    """The channel, references as on the schematic. Both relay poles mute in parallel, so one
    switch with half a contact's resistance stands for them."""
    return f"""\
{supply}
R40 sup v9f 100
C20 v9f 0 100u
C21 v9f 0 100n
R38 v9f vref 47k
R39 vref 0 47k
C19 vref 0 100u
{hpl}
C16 hpl cin 10u
R28 cin tap 9.1k
R29 tap vref 1k
SLINE padcom cin linectl 0 PADSW
SMIC padcom tap micctl 0 PADSW
VLINE linectl 0 {{1-({mic})}}
VMIC micctl 0 {{{mic}}}
R30 padcom x 1k
R31 x vref 100k
SMUTE x vref mutectl 0 RELAY
VMUTE mutectl 0 {mute}
XU5A x aout aout v9f 0 OPAMP_OPA2197
R32 aout invn 10k
R33 invn bout 10k
XU5B vref invn bout v9f 0 OPAMP_OPA2197
R34 aout h 100
C17 h hc 47u Rser={esr}
R41 hc hot 10
D8 h v9f DSCH
D9 0 h DSCH
R36 hot 0 100k
R35 bout cn 100
C18 cn cc {c18} Rser={esr}
R42 cc cold 10
D10 cn v9f DSCH
D11 0 cn DSCH
R37 cold 0 100k
"""


def deck(title, body, analysis, extra=''):
    return f"* {title}\n{body}{extra}{OPAMP}{MODELS}{analysis}\n.end\n"


def tests():
    out = {}
    # ---- ac: a 10 kOhm-per-leg line input, the receiver's ground the pedal's
    rx = "RRH hot 0 10k\nRRC cold 0 10k\n"
    for name, mic, mute in (('ac-line', '0', '0'), ('ac-mic', '1', '0'), ('ac-muted', '0', '1')):
        out[name] = deck(name, channel(mic=mic, mute=mute) + rx, '.ac dec 40 0.1 500k')
    # ---- cmrr: signal off; 1 V between the receiver's ground and the pedal's
    for tag, c18 in (('matched', '47u'), ('5pct', '49.35u'), ('20pct', '56.4u')):
        body = channel(c18=c18, hpl='VHP hpl 0 DC 1.65 AC 0')
        body += "RRH hot rgnd 10k\nRRC cold rgnd 10k\nVCM rgnd 0 DC 0 AC 1\n"
        out[f'cmrr-{tag}'] = deck(f'cmrr {tag}', body, '.ac dec 40 10 100k')
    # ---- powerup: 9 V at 0; VMID rises 1-1.5 s (the codec booting); mute releases at 15 s;
    # signal (-1 dBFS, 1 kHz) from 20 s
    sup = 'VSUP sup 0 PWL(0 0 1m 9)'
    hp = ('VHP hpl 0 PWL(0 0 1 0 1.5 1.65 20 1.65)\n'
          'VSIG hpls hpl SINE(0 1.26 1k 20)').replace('VHP hpl', 'VHP hplb').replace(
              'VSIG hpls hpl', 'VSIG hpl hplb')
    body = channel(supply=sup, hpl=hp, mute='PWL(0 1 15 1 15.001 0)') + rx
    meas = (".meas TRAN thump_boot MAX abs(V(hot,cold)) FROM 0 TO 14.9\n"
            ".meas TRAN cm_boot MAX abs(V(hot)+V(cold))/2 FROM 0 TO 14.9\n"
            ".meas TRAN thump_release MAX abs(V(hot,cold)) FROM 14.99 TO 19.99\n"
            ".meas TRAN sig_pp PP V(hot,cold) FROM 20.01 TO 20.02\n"
            ".meas TRAN hot_pp PP V(hot) FROM 20.01 TO 20.02\n"
            ".meas TRAN cold_pp PP V(cold) FROM 20.01 TO 20.02\n")
    out['powerup'] = deck('powerup', body, '.tran 0 20.02 0 1m\n.options plotwinsize=0', meas)
    # ---- phantom: playing, no signal. 48 V through 6.81 kOhm on each pin, on at 1 s; hot
    # shorted to pin 1 (the receiver's ground) for 10 ms at 3 s.
    body = channel() + (
        "VPH p48 0 PWL(0 0 1 0 1.0001 48)\n"
        "RPH hot p48 6.81k\nRPC cold p48 6.81k\n"
        "SSHORT hot 0 shortctl 0 RELAY\nVSHORT shortctl 0 PWL(0 0 3 0 3.0001 1 3.01 1 3.0101 0)\n")
    meas = (".meas TRAN hot_dc FIND V(hot) AT 2.9\n"
            ".meas TRAN h_max MAX V(h) FROM 0.9 TO 4\n"
            ".meas TRAN h_min MIN V(h) FROM 0.9 TO 4\n"
            ".meas TRAN id9_peak MAX I(D9) FROM 2.99 TO 3.02\n"
            ".meas TRAN id8_peak MAX I(D8) FROM 0.9 TO 4\n"
            ".meas TRAN iop_peak MAX abs(I(R34)) FROM 0.9 TO 4\n"
            ".meas TRAN id9_charge INTEG I(D9) FROM 2.999 TO 3.01\n")
    out['phantom'] = deck('phantom', body, '.tran 0 4 0 100u\n.options plotwinsize=0', meas)
    return out


def read_text(path):
    raw = path.read_bytes()
    if raw[:2] in (b'\xff\xfe', b'\xfe\xff') or (len(raw) > 1 and raw[1] == 0):
        return raw.decode('utf-16-le', errors='replace').lstrip('﻿')
    return raw.decode('latin-1')


def read_ac(path):
    """A binary LTspice .raw from an AC run: {variable: [(freq, complex)]}. The header is
    UTF-16, ending in 'Binary:'; every value after it is a complex double."""
    import struct
    raw = path.read_bytes()
    marker = 'Binary:\n'.encode('utf-16-le')
    cut = raw.index(marker) + len(marker)
    head = raw[:cut].decode('utf-16-le')
    names = re.findall(r'^\s*\d+\s+(\S+)\s+\S+\s*$', head.split('Variables:', 1)[1], re.M)
    npts = int(re.search(r'No. Points:\s*(\d+)', head).group(1))
    n = len(names)
    vals = struct.unpack(f'<{2 * n * npts}d', raw[cut:cut + 16 * n * npts])
    out = {nm.lower(): [] for nm in names}
    for i in range(npts):
        row = vals[2 * n * i: 2 * n * (i + 1)]
        f = row[0]
        for k, nm in enumerate(names):
            out[nm.lower()].append((f, complex(row[2 * k], row[2 * k + 1])))
    return out


def diff(data, a, b):
    return [(f, va - vb) for (f, va), (_, vb) in zip(data[f'v({a})'], data[f'v({b})'])]


def at(series, f0):
    return min(series, key=lambda p: abs(math.log(p[0] / f0)))[1]


def corners(series, ref):
    """-3 dB below and above the band, relative to the 1 kHz figure."""
    target = abs(ref) / math.sqrt(2)
    lo = hi = None
    for (f1, v1), (f2, v2) in zip(series, series[1:]):
        if lo is None and abs(v1) < target <= abs(v2):
            lo = f1
        if abs(v1) >= target > abs(v2):
            hi = f2
    return lo, hi


def db(v):
    return 20 * math.log10(abs(v)) if abs(v) else float('-inf')


def read_meas(path):
    text = read_text(path)
    return {m.group(1): float(m.group(2))
            for m in re.finditer(r'^(\w+): .*?=\s*([-+0-9.eE]+)', text, re.M)}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    today = datetime.date.today().isoformat()
    ap.add_argument('--out', type=Path, default=ROOT / 'bench-results' / f'{today}-balanced-output-sim')
    ap.add_argument('--ltspice', default=LTSPICE)
    ap.add_argument('--keep-raw', action='store_true',
                    help='keep LTspice\'s .raw waveforms (tens of MB; the script rebuilds them)')
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    decks = tests()
    for name, text in decks.items():
        cir = args.out / f'{name}.cir'
        cir.write_text(text)
        r = subprocess.run([args.ltspice, '-b', cir.name], cwd=args.out,
                           capture_output=True, timeout=600)
        if r.returncode:
            sys.exit(f'{name}: LTspice exited {r.returncode}')
        if 'error' in read_text(args.out / f'{name}.log').lower().replace('errors: 0', ''):
            print(f'warning: {name}.log mentions an error; read it')

    lines, res = [], {}
    for name in ('ac-line', 'ac-mic', 'ac-muted'):
        d = read_ac(args.out / f'{name}.raw')
        dif, hot, cold = diff(d, 'hot', 'cold'), d['v(hot)'], d['v(cold)']
        g = at(dif, 1e3)
        lo, hi = corners(dif, g)
        res[name] = dict(diff_db=db(g), hot_db=db(at(hot, 1e3)), cold_db=db(at(cold, 1e3)),
                         sym_db=db(at(hot, 1e3)) - db(at(cold, 1e3)),
                         phase=math.degrees(math.atan2((at(cold, 1e3) / at(hot, 1e3)).imag,
                                                       (at(cold, 1e3) / at(hot, 1e3)).real)),
                         lo=lo, hi=hi)
    for tag in ('matched', '5pct', '20pct'):
        d = read_ac(args.out / f'cmrr-{tag}.raw')
        dif = diff(d, 'hot', 'cold')
        res[f'cmrr-{tag}'] = {f: -db(at(dif, f)) for f in (50, 1000)}
    res['powerup'] = read_meas(args.out / 'powerup.log')
    res['phantom'] = read_meas(args.out / 'phantom.log')

    L = lines.append
    L(f'# One balanced output channel, simulated ({today})\n')
    L('Written by `schematic/balanced-output-sim.py` (LTspice 17, batch mode). The circuit is '
      '`schematic/balanced-output/balanced-output.kicad_sch`; the design is '
      '[docs/balanced-outputs.md](../../docs/balanced-outputs.md). The op-amp is a behavioural '
      'model (10 MHz, rail-to-rail, no current limit), so read the numbers as the circuit\'s, '
      'not the part\'s.\n')
    L('## Gain, symmetry and the mute (1 kHz; the receiver is 10 kΩ per leg)\n')
    L('| Case | pin 2 − pin 3 | pin 2 | pin 3 | pin 2 vs pin 3 | phase, 3 vs 2 | −3 dB low | −3 dB high |')
    L('|---|---|---|---|---|---|---|---|')
    for name, label in (('ac-line', 'Line'), ('ac-mic', 'Mic'), ('ac-muted', 'Line, muted')):
        r = res[name]
        f = lambda x: '—' if x is None else (f'{x:.2f} Hz' if x < 1e3 else f'{x / 1e3:.0f} kHz')
        L(f"| {label} | {r['diff_db']:+.2f} dB | {r['hot_db']:+.2f} dB | {r['cold_db']:+.2f} dB | "
          f"{r['sym_db']:+.3f} dB | {r['phase']:.1f}° | {f(r['lo'])} | {f(r['hi'])} |")
    L('\n0 dB is the codec\'s own level at HPL (1.0 V rms at full scale), so Line\'s +6.02 dB is '
      '2.0 V rms, +8.2 dBu, between pins 2 and 3.\n')
    L('## Rejection of a voltage between the two grounds\n')
    L('1 V between the receiver\'s ground and the pedal\'s; what appears between pins 2 and 3.\n')
    L('| C17 and C18 | at 50 Hz | at 1 kHz |')
    L('|---|---|---|')
    for tag, label in (('matched', 'matched'), ('5pct', '5 % apart'), ('20pct', '20 % apart')):
        r = res[f'cmrr-{tag}']
        L(f'| {label} | {r[50]:.1f} dB | {r[1000]:.1f} dB |')
    L('\nThe receiver here is ideal: in the room its own rejection adds to these, or limits '
      'them.\n')
    p = res['powerup']
    L('## Power-up, the mute, and signal\n')
    L(f"- Largest voltage between pins 2 and 3 while muted (9 V arriving, VMID rising): "
      f"**{p.get('thump_boot', float('nan')) * 1e3:.2f} mV**; largest common-mode voltage: "
      f"{p.get('cm_boot', float('nan')):.2f} V, which a balanced input rejects.")
    L(f"- Largest voltage between pins 2 and 3 in the 5 s after the mute releases: "
      f"**{p.get('thump_release', float('nan')) * 1e3:.2f} mV**.")
    L(f"- Then −1 dBFS at 1 kHz: {p.get('sig_pp', float('nan')):.2f} V peak-to-peak between "
      f"pins 2 and 3 ({p.get('hot_pp', float('nan')):.2f} V on pin 2, "
      f"{p.get('cold_pp', float('nan')):.2f} V on pin 3).\n")
    ph = res['phantom']
    L('## Phantom power, then a short\n')
    L('48 V through 6.81 kΩ onto each pin at 1 s; pin 2 shorted to pin 1 for 10 ms at 3 s. '
      'Capacitor ESR 0.5 Ω.\n')
    L(f"- Pin 2 settles at {ph.get('hot_dc', float('nan')):.1f} V with phantom on.")
    L(f"- The driver side of C17 (node H) stays between {ph.get('h_min', float('nan')):.2f} V and "
      f"{ph.get('h_max', float('nan')):.2f} V (the op-amp's rails are 0 V and 9 V).")
    L(f"- Peak current in D9 when pin 2 shorts: **{ph.get('id9_peak', float('nan')):.1f} A**, "
      f"{ph.get('id9_charge', float('nan')) * 1e3:.2f} mC in all; peak in D8 when phantom comes "
      f"on: {ph.get('id8_peak', float('nan')) * 1e3:.1f} mA.")
    L(f"- Peak current the op-amp would carry, through R34: "
      f"**{ph.get('iop_peak', float('nan')) * 1e3:.0f} mA** (the OPA2197 limits at about "
      f"±65 mA).\n")
    (args.out / 'README.md').write_text('\n'.join(lines) + '\n')
    if not args.keep_raw:
        for raw in args.out.glob('*.raw'):
            raw.unlink()
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
